import { execFileSync } from "node:child_process";
import { copyFileSync, cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const cwd = fileURLToPath(new URL("../", import.meta.url));
const run = (command: string, args: string[], input?: string): string =>
	execFileSync(command, args, { cwd, input, encoding: "utf8", stdio: ["pipe", "pipe", "inherit"] });
// Cargo.toml owns the version; manifests are checked mirrors for their package formats.
const version = /^version = "([^"]+)"$/m.exec(readFileSync(new URL("../../Cargo.toml", import.meta.url), "utf8"))?.[1];
for (const manifest of ["../../package.json", "../package.json"]) {
	if (JSON.parse(readFileSync(new URL(manifest, import.meta.url), "utf8")).version !== version)
		throw new Error("Package version differs from Cargo.toml");
}
const generated = execFileSync("node", ["scripts/cargo.mjs", "run", "--locked", "--quiet", "--example", "types"], {
	cwd: root,
	encoding: "utf8",
});
const types = execFileSync(
	`${root}node_modules/.bin/biome`,
	["format", `--config-path=${root}biome.json`, "--stdin-file-path=protocol.ts"],
	{ cwd: root, input: generated, encoding: "utf8" },
);
const protocol = new URL("../src/protocol.ts", import.meta.url);
if (process.argv.includes("--check-protocol") || process.argv.includes("--check-types")) {
	if (readFileSync(protocol, "utf8") !== types) throw new Error("Generated protocol is stale; run bun run protocol:generate");
	console.log("PROTOCOL_CHECK_PASS: exact Rust-generated bytes");
} else writeFileSync(protocol, types);
if (process.argv.some((arg) => ["--protocol", "--check-protocol", "--check-types"].includes(arg))) process.exit(0);
if (run("wasm-bindgen", ["--version"]).trim() !== "wasm-bindgen 0.2.105") throw new Error("Build requires wasm-bindgen-cli 0.2.105");
execFileSync("node", ["scripts/cargo.mjs", "build", "--locked", "--target", "wasm32-unknown-unknown", "--release"], {
	cwd: root,
	stdio: "inherit",
});
rmSync(new URL("../dist", import.meta.url), { recursive: true, force: true });
rmSync(new URL("../generated/wasm", import.meta.url), { recursive: true, force: true });
run("wasm-bindgen", ["--target", "web", "--out-dir", "generated/wasm", "../target/wasm32-unknown-unknown/release/realine_core.wasm"]);
run(`${root}node_modules/.bin/tsc`, ["-p", "tsconfig.build.json"]);
for (const file of [
	"API.md",
	"BUILD.md",
	"CORE_CONTRACT.md",
	"LISTS_CONTRACT.md",
	"WINDOW_CONTRACT.md",
	"LICENSE",
	"LICENSE-MIT",
	"LICENSE-APACHE",
	"THIRD-PARTY-NOTICES.md",
]) {
	copyFileSync(new URL(`../../${file}`, import.meta.url), new URL(`../dist/${file}`, import.meta.url));
}
mkdirSync(new URL("../dist/licenses", import.meta.url), { recursive: true });
cpSync(new URL("../../licenses", import.meta.url), new URL("../dist/licenses", import.meta.url), { recursive: true });
console.log("REALINE_BUILD_PASS: native-generated protocol, Wasm, ESM and declarations");
